import { AlertRepository } from '../repositories/AlertRepository';
import { IncidentRepository } from '../repositories/IncidentRepository';
import { TelegramService } from './TelegramService';
import { MetricSample, Severity } from '../types';

export class AlertService {
  /**
   * Evaluates live metric samples against threshold-based alert rules.
   */
  static async evaluateSampleRules(sample: MetricSample): Promise<void> {
    const rules = await AlertRepository.findEnabledRules();
    const now = Date.now();

    for (const rule of rules) {
      let currentValue: number | undefined;

      if (rule.metric_type === 'cpu') currentValue = sample.cpu_utilization;
      else if (rule.metric_type === 'memory') currentValue = sample.memory_utilization;
      else if (rule.metric_type === 'disk') currentValue = sample.disk_utilization;
      else if (rule.metric_type === 'network_rx') currentValue = sample.network_rx_bytes_sec;
      else if (rule.metric_type === 'network_tx') currentValue = sample.network_tx_bytes_sec;

      if (currentValue === undefined) continue;

      let triggered = false;
      if (rule.condition === 'gt' && currentValue > rule.threshold_value) {
        triggered = true;
      } else if (rule.condition === 'lt' && currentValue < rule.threshold_value) {
        triggered = true;
      }

      if (triggered) {
        await this.handleRuleTrigger(rule, sample.host_id, currentValue, 
          `Rule "${rule.name}" triggered: observed ${currentValue.toFixed(2)} exceeded threshold of ${rule.threshold_value}.`);
      }
    }
  }

  /**
   * Evaluates statistical anomalies identified by the MATLAB engine.
   */
  static async evaluateAnomalyAlert(anomaly: {
    host_id: string;
    metric_type: string;
    observed_value: number;
    z_score: number;
    severity: Severity;
    explanation: string;
  }): Promise<void> {
    const rules = await AlertRepository.findEnabledRules();
    for (const rule of rules) {
      if (rule.metric_type === anomaly.metric_type && rule.condition === 'z_score_gt') {
        if (Math.abs(anomaly.z_score) >= rule.threshold_value) {
          await this.handleRuleTrigger(
            rule,
            anomaly.host_id,
            anomaly.observed_value,
            `MATLAB Statistical Anomaly: Z-Score = ${anomaly.z_score.toFixed(2)} (threshold: ${rule.threshold_value}). ${anomaly.explanation}`
          );
        }
      }
    }
  }

  /**
   * Evaluates disk capacity exhaustion forecasts generated by MATLAB.
   */
  static async evaluateForecastAlert(forecast: {
    host_id: string;
    metric_type: string;
    current_value: number;
    time_to_exhaustion_hours: number | null;
    reason: string;
  }): Promise<void> {
    if (forecast.time_to_exhaustion_hours === null || isNaN(forecast.time_to_exhaustion_hours)) {
      return;
    }

    const rules = await AlertRepository.findEnabledRules();
    for (const rule of rules) {
      if (rule.metric_type === forecast.metric_type && rule.condition === 'tte_lt') {
        if (forecast.time_to_exhaustion_hours < rule.threshold_value) {
          await this.handleRuleTrigger(
            rule,
            forecast.host_id,
            forecast.current_value,
            `MATLAB Capacity Forecast Alert: Projected time to exhaustion is ${forecast.time_to_exhaustion_hours.toFixed(1)} hours (threshold: ${rule.threshold_value} hrs). ${forecast.reason}`
          );
        }
      }
    }
  }

  private static async handleRuleTrigger(
    rule: any,
    hostId: string,
    currentValue: number,
    summary: string
  ): Promise<void> {
    // 1. Check rule cooldown to avoid alert storms
    if (rule.last_triggered_at) {
      const msSinceLast = Date.now() - new Date(rule.last_triggered_at).getTime();
      const cooldownMs = rule.cooldown_minutes * 60 * 1000;
      if (msSinceLast < cooldownMs) {
        return; // Suppressed by rule cooldown
      }
    }

    // 2. Deduplicate against existing active incidents on this host & metric
    const activeIncident = await IncidentRepository.findActiveByMetric(hostId, rule.metric_type);
    if (activeIncident) {
      return; // Already an open or acknowledged incident
    }

    // 3. Create new incident
    const incident = await IncidentRepository.insert({
      host_id: hostId,
      title: rule.name,
      severity: rule.severity,
      status: 'open',
      trigger_metric: rule.metric_type,
      trigger_value: currentValue,
      summary,
    });

    await AlertRepository.updateLastTriggered(rule.id);

    // 4. Dispatch Telegram notification if configured or rule has telegram enabled
    const msg = TelegramService.formatIncidentAlert(incident);
    await TelegramService.sendAlert(msg, incident.id);
  }
}
