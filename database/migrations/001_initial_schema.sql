-- Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Hosts Table
CREATE TABLE IF NOT EXISTS hosts (
    id VARCHAR(64) PRIMARY KEY,
    hostname VARCHAR(255) NOT NULL,
    ip_address VARCHAR(45),
    os_info TEXT,
    cpu_count INTEGER NOT NULL DEFAULT 1,
    total_memory_bytes BIGINT NOT NULL DEFAULT 0,
    total_disk_bytes BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'online' CHECK (status IN ('online', 'warning', 'critical', 'offline')),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_hosts_status ON hosts(status);
CREATE INDEX IF NOT EXISTS idx_hosts_last_seen ON hosts(last_seen_at);

-- 2. Metric Samples Table
CREATE TABLE IF NOT EXISTS metric_samples (
    id BIGSERIAL PRIMARY KEY,
    host_id VARCHAR(64) NOT NULL REFERENCES hosts(id) ON DELETE CASCADE,
    timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    cpu_utilization DOUBLE PRECISION NOT NULL CHECK (cpu_utilization >= 0 AND cpu_utilization <= 100),
    cpu_load_1m DOUBLE PRECISION NOT NULL DEFAULT 0,
    cpu_load_5m DOUBLE PRECISION NOT NULL DEFAULT 0,
    cpu_load_15m DOUBLE PRECISION NOT NULL DEFAULT 0,
    memory_utilization DOUBLE PRECISION NOT NULL CHECK (memory_utilization >= 0 AND memory_utilization <= 100),
    memory_used_bytes BIGINT NOT NULL DEFAULT 0,
    memory_total_bytes BIGINT NOT NULL DEFAULT 0,
    disk_utilization DOUBLE PRECISION NOT NULL CHECK (disk_utilization >= 0 AND disk_utilization <= 100),
    disk_used_bytes BIGINT NOT NULL DEFAULT 0,
    disk_total_bytes BIGINT NOT NULL DEFAULT 0,
    network_rx_bytes_sec DOUBLE PRECISION NOT NULL DEFAULT 0,
    network_tx_bytes_sec DOUBLE PRECISION NOT NULL DEFAULT 0,
    availability BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_metric_samples_host_time ON metric_samples(host_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_metric_samples_time ON metric_samples(timestamp DESC);

-- 3. Analysis Results Table (Generated by MATLAB)
CREATE TABLE IF NOT EXISTS analysis_results (
    id BIGSERIAL PRIMARY KEY,
    host_id VARCHAR(64) NOT NULL REFERENCES hosts(id) ON DELETE CASCADE,
    analysis_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metric_type VARCHAR(32) NOT NULL CHECK (metric_type IN ('cpu', 'memory', 'disk', 'network_rx', 'network_tx')),
    mean DOUBLE PRECISION NOT NULL,
    median DOUBLE PRECISION NOT NULL,
    std_dev DOUBLE PRECISION NOT NULL,
    min_val DOUBLE PRECISION NOT NULL,
    max_val DOUBLE PRECISION NOT NULL,
    p25 DOUBLE PRECISION NOT NULL,
    p75 DOUBLE PRECISION NOT NULL,
    p90 DOUBLE PRECISION NOT NULL,
    p95 DOUBLE PRECISION NOT NULL,
    p99 DOUBLE PRECISION NOT NULL,
    trend_slope DOUBLE PRECISION NOT NULL DEFAULT 0,
    trend_intercept DOUBLE PRECISION NOT NULL DEFAULT 0,
    r_squared DOUBLE PRECISION NOT NULL DEFAULT 0,
    mae DOUBLE PRECISION NOT NULL DEFAULT 0,
    rmse DOUBLE PRECISION NOT NULL DEFAULT 0,
    forecast_exhaustion_hours DOUBLE PRECISION,
    forecast_exhaustion_timestamp TIMESTAMPTZ,
    sample_count INTEGER NOT NULL,
    window_minutes INTEGER NOT NULL,
    engine_used VARCHAR(64) NOT NULL DEFAULT 'MATLAB Engine',
    raw_details JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_analysis_results_host_metric ON analysis_results(host_id, metric_type, analysis_timestamp DESC);

-- 4. Anomalies Table (Detected by MATLAB Statistical Detector)
CREATE TABLE IF NOT EXISTS anomalies (
    id BIGSERIAL PRIMARY KEY,
    host_id VARCHAR(64) NOT NULL REFERENCES hosts(id) ON DELETE CASCADE,
    metric_type VARCHAR(32) NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    observed_value DOUBLE PRECISION NOT NULL,
    baseline_mean DOUBLE PRECISION NOT NULL,
    baseline_std DOUBLE PRECISION NOT NULL,
    z_score DOUBLE PRECISION NOT NULL,
    threshold DOUBLE PRECISION NOT NULL,
    severity VARCHAR(32) NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    explanation TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'investigating', 'resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_anomalies_host_status ON anomalies(host_id, status, detected_at DESC);
CREATE INDEX IF NOT EXISTS idx_anomalies_detected_at ON anomalies(detected_at DESC);

-- 5. Incidents Table
CREATE TABLE IF NOT EXISTS incidents (
    id BIGSERIAL PRIMARY KEY,
    host_id VARCHAR(64) NOT NULL REFERENCES hosts(id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    severity VARCHAR(32) NOT NULL CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    status VARCHAR(32) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'acknowledged', 'resolved')),
    trigger_metric VARCHAR(64) NOT NULL,
    trigger_value DOUBLE PRECISION NOT NULL,
    summary TEXT NOT NULL,
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by VARCHAR(128),
    resolved_at TIMESTAMPTZ,
    resolution_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_incidents_host_status ON incidents(host_id, status, created_at DESC);

-- 6. Alert Rules Table
CREATE TABLE IF NOT EXISTS alert_rules (
    id SERIAL PRIMARY KEY,
    name VARCHAR(128) NOT NULL,
    metric_type VARCHAR(32) NOT NULL,
    condition VARCHAR(32) NOT NULL CHECK (condition IN ('gt', 'lt', 'z_score_gt', 'tte_lt')),
    threshold_value DOUBLE PRECISION NOT NULL,
    duration_seconds INTEGER NOT NULL DEFAULT 60,
    severity VARCHAR(32) NOT NULL DEFAULT 'high' CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    cooldown_minutes INTEGER NOT NULL DEFAULT 15,
    last_triggered_at TIMESTAMPTZ,
    notify_telegram BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 7. Notification Logs Table
CREATE TABLE IF NOT EXISTS notification_logs (
    id BIGSERIAL PRIMARY KEY,
    incident_id BIGINT REFERENCES incidents(id) ON DELETE SET NULL,
    channel VARCHAR(32) NOT NULL,
    recipient VARCHAR(128) NOT NULL,
    message TEXT NOT NULL,
    status VARCHAR(32) NOT NULL CHECK (status IN ('sent', 'failed', 'skipped')),
    error_message TEXT,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_notification_logs_incident ON notification_logs(incident_id);
